const pick = (lines) => lines[Math.floor(Math.random() * lines.length)];

export function petLine(pool, profile) {
  const set = LINES[pool];
  if (!set) return "";
  const personal = profile?.primaryPersonality && set[profile.primaryPersonality];
  const chosen = personal && Math.random() < 0.6 ? personal : set.default;
  return pick(chosen);
}
