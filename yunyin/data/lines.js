export function pickLine(rand, now = Date.now()) {
  const h = new Date(now).getHours();
  const pool = h < 6 ? LINES.night : h < 11 ? LINES.morning : h < 18 ? LINES.day : h < 22 ? LINES.evening : LINES.night;
  return pool[Math.floor(rand() * pool.length)];
}
